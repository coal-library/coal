#!/usr/bin/env python3
"""Measure the dynamic AABB tree's per-leaf virtual dispatch, and its dilution.

The experiment
--------------
The first thing leafCollide() does on invocation is test whether either leaf
node is a plane or half space. Ultimately, this reduces to a number of virtual
calls (CollisionObject::getNodeType() invokes virtual
CollisionGeometry::getNodeType()). Virtual method invocations (particularly if
branch predictions fail) impart a cost. This benchmark is intended to
illustrate that cost.

This benchmark sets up a grid of plate-like objects. To make sure branch
prediction, the objects consists of boxes, cylinders, and ellipsoids, all with
identical bounding boxes. There are no planes or halfspaces. Their relative
positions are defined in two configurations:

  - Narrowphase-bound: the plates are tilted 20 degrees. This guarantees many
    invocations of leafCollide() and a high proportion of those invocations
    lead to narrowphase work.
  - Broadphase-bound: the plates are tilted 5 degrees. This leads to a fewer
    number of leafCollide() invocations and none of those invocations lead to
    narrowphase work.

The narrowphase-bound configuration illustrates the minimum penalty for the
virtual methods because the narrowphase geometry collision work dominates the
cost. The broadphase-bound configuration illustrates the maximum penalty. In
general, we would assume that the penalty in a typical scene would lie
somewhere between.

Reading the output
------------------

Running this script against Coal will produce a table like this:

config              tilt   AABB h  candidates traversal (μs) pipeline (μs) narrow (μs/cand)
-------------------------------------------------------------------------------------------
narrowphase-bound    20°   0.1073        7424          91.8       4309.7          0.568
broadphase-bound      5°   0.0311           0          37.5         37.4              -

For each configuration, the table reports:
  - The configuration's name
  - The plate properties: its tilt and the height of the resultant AABB.
  - The number of narrowphase candidate pairs generated by the broadphase.
    These are traversal leaf paris whose bounding boxes overlap and lead to
    narrowphase collision checks.
  - The time spent purely traversing the BVH, in microseconds.
  - The total time spent on both traversal and narrowphase, in microseconds.
  - The narrowphase time per candidate, in microseconds.

Needs Coal's Python bindings on PYTHONPATH, e.g.:

    PYTHONPATH=<build>/python-nb test/benchmark/leaf_dispatch_bench.py

Nothing here depends on the rest of the branch, so checking out the commit that
adds this file measures devel, and later commits are measured the same way.
"""

import argparse
import math
import statistics
import sys
import time

import coal
import numpy as np

# Plate dimensions, meters. Thin, so that tilting one changes the height of
# its AABB far more than it changes where the plate itself sits.
PLATE_W = 0.30
PLATE_T = 0.005

PITCH_XY = 0.40  # > PLATE_W, so columns never overlap each other
PITCH_Z = 0.05  # vertical spacing within a column

# name, tilt in degrees, whether adjacent plates' AABBs are expected to overlap
CONFIGS = (
    ("narrowphase-bound", 20.0, True),
    ("broadphase-bound", 5.0, False),
)


def plate_geometries():
    """Flat plates of identical bounding box but differing geometry class."""
    return [
        coal.Box(PLATE_W, PLATE_W, PLATE_T),
        coal.Cylinder(PLATE_W / 2, PLATE_T),
        coal.Ellipsoid(PLATE_W / 2, PLATE_W / 2, PLATE_T / 2),
    ]


def aabb_height(tilt_deg: float) -> float:
    """Full z extent of one plate's AABB when tilted `tilt_deg` about x."""
    t = math.radians(tilt_deg)
    return PLATE_W * abs(math.sin(t)) + PLATE_T * abs(math.cos(t))


def build(n: int, tilt_deg: float):
    """A grid of identically tilted plates.  Returns (manager, objects)."""
    side = max(1, round(n ** (1 / 3)))
    t = math.radians(tilt_deg)
    R = np.array(
        [
            [1.0, 0.0, 0.0],
            [0.0, math.cos(t), -math.sin(t)],
            [0.0, math.sin(t), math.cos(t)],
        ]
    )

    geoms = plate_geometries()
    objs = []
    for i in range(side):
        for j in range(side):
            for k in range(side):
                o = coal.CollisionObject(geoms[len(objs) % len(geoms)])
                o.setTransform(
                    coal.Transform3s(
                        R, np.array([i * PITCH_XY, j * PITCH_XY, k * PITCH_Z])
                    )
                )
                o.computeAABB()
                objs.append(o)

    mgr = coal.DynamicAABBTreeCollisionManager()
    for o in objs:
        mgr.registerObject(o)
    mgr.setup()
    return mgr, objs


def check_scene(objs, tilt_deg: float, expect_overlap: bool) -> None:
    """Confirm the configuration is the one the docstring describes."""
    # objs[k] and objs[k+1] are adjacent in z within one column.  Checking
    # several consecutive k also covers every pairing of geometry classes.
    assert len(objs) > 8, "need at least a 2x2x2 grid"
    for k in range(6):
        a, b = objs[k], objs[k + 1]
        overlaps = a.getAABB().overlap(b.getAABB())
        assert overlaps == expect_overlap, (
            f"tilt {tilt_deg} deg: adjacent AABBs overlap={overlaps}, "
            f"expected {expect_overlap}"
        )
        # ... and that an overlapping pair is nonetheless not a real collision.
        if expect_overlap:
            res = coal.CollisionResult()
            coal.collide(a, b, coal.CollisionRequest(), res)
            assert not res.isCollision(), "plates intersect; they must not"


def time_collide(mgr, cb, reps: int) -> float:
    """Median microseconds for one mgr.collide(cb)."""
    samples = []
    for _ in range(reps):
        t0 = time.perf_counter()
        mgr.collide(cb)
        t1 = time.perf_counter()
        samples.append((t1 - t0) * 1e6)
    return statistics.median(samples)


def main() -> int:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("-n", type=int, default=4096, help="object count (default 4096)")
    p.add_argument("--reps", type=int, default=50, help="timed collide() calls")
    p.add_argument("--label", default="", help="name for this build, e.g. 'devel'")
    args = p.parse_args()

    kinds = ", ".join(
        str(coal.CollisionObject(g).getNodeType()).split(".")[-1]
        for g in plate_geometries()
    )
    print(
        f"coal {getattr(coal, '__version__', '?')}"
        + (f"   build: {args.label}" if args.label else "")
    )
    print(
        f"{args.n} plates {PLATE_W}x{PLATE_W}x{PLATE_T} m; columns pitched "
        f"{PITCH_XY} m, plates {PITCH_Z} m apart in z"
    )
    print(f"geometries: {kinds}; medians of {args.reps} reps\n")

    header = (
        f"{'config':<18} {'tilt':>5} {'AABB h':>8} {'candidates':>11} "
        f"{'traversal (μs)':>13} {'pipeline (μs)':>12} {'narrow (μs/cand)':>15}"
    )
    print(header)
    print("-" * len(header))

    for name, tilt, expect_overlap in CONFIGS:
        mgr, objs = build(args.n, tilt)
        check_scene(objs, tilt, expect_overlap)

        # Traversal alone: this callback only appends the pair to a vector.
        collect_narrowphase_candidates = coal.CollisionCallBackCollect(
            max(16, 8 * len(objs))
        )
        traversal_us = time_collide(mgr, collect_narrowphase_candidates, args.reps)
        candidates = collect_narrowphase_candidates.numCollisionPairs()

        # Traversal plus what a caller actually does with each candidate.
        resolve_narrowphase = coal.CollisionCallBackDefault()
        pipeline_us = time_collide(mgr, resolve_narrowphase, args.reps)
        # defaultCollisionFunction() stops the traversal once it has collected
        # request.num_max_contacts contacts. This scene must produce none, or
        # the pipeline column is timing a truncated traversal.
        assert resolve_narrowphase.data.result.numContacts() == 0, (
            "scene produced a contact; the narrowphase traversal stopped early "
            "and the pipeline timing is not comparable"
        )

        narrow = (
            f"{(pipeline_us - traversal_us) / candidates:>15.3f}"
            if candidates
            else f"{'-':>15}"
        )
        print(
            f"{name:<18} {tilt:>4.0f}° {aabb_height(tilt):>8.4f} "
            f"{candidates:>11} {traversal_us:>13.1f} {pipeline_us:>12.1f}{narrow}"
        )

    return 0


if __name__ == "__main__":
    sys.exit(main())
